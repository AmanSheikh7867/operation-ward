"""
Operation Ward Zero - Model Training
=====================================

MODEL CARD (Experimental - Hospital ICU Grade)
-----------------------------------------------
- Model type:       RandomForestRegressor (scikit-learn ensemble)
- Task:             Regression on multi-vital physiological risk score (0-1)
- Features (10):    hr, spo2, sys, dia, temp, rr, glucose, map, shock_index, hrv
- Target:           Synthetic risk score generated by clinical-rule heuristics and NEWS2
- Training data:    8,000 synthetic samples across physiological clusters:
                    * Normal Resting Baseline
                    * Sepsis / SIRS Onset (High RR, Fever, Low MAP, High Shock Index)
                    * Acute Respiratory Failure (Hypoxemia, Severe Tachypnea)
                    * Hypoglycemic Shock (Glucose < 60, Autonomic Strain)
                    * Hypertensive Crisis (Malignant Hypertension)
                    * Random Physiological Fluctuations
- Limitations:
    * The model learns to reproduce clinical-rule risk metrics.
    * Output should be labelled "experimental risk score" only.
    * It does not replace clinical judgment or certified medical devices.
- Random seeds:     Data generation seed=42, model random_state=42

Usage:
    python -m ml.train          # from project root
    python ml/train.py          # direct execution
"""

import os
import sys
import json
import time
import pathlib
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split

try:
    import joblib
except ImportError:
    from sklearn.externals import joblib  # type: ignore

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
_THIS_DIR = pathlib.Path(__file__).resolve().parent
ARTIFACTS_DIR = _THIS_DIR / "artifacts"
REPORTS_DIR = _THIS_DIR / "reports"

ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
REPORTS_DIR.mkdir(parents=True, exist_ok=True)

MODEL_PATH = ARTIFACTS_DIR / "risk_model.joblib"
SCALER_PATH = ARTIFACTS_DIR / "feature_stats.joblib"
TRAIN_REPORT_PATH = REPORTS_DIR / "training_report.json"

# ---------------------------------------------------------------------------
# Feature names & safe ranges (10 Hospital Telemetry Features)
# ---------------------------------------------------------------------------
FEATURE_NAMES = [
    "hr",          # Heart Rate (bpm)
    "spo2",        # Blood Oxygen (%)
    "sys",         # Systolic Blood Pressure (mmHg)
    "dia",         # Diastolic Blood Pressure (mmHg)
    "temp",        # Core Temperature (°C)
    "rr",          # Respiratory Rate (breaths/min)
    "glucose",     # Capillary Blood Glucose (mg/dL)
    "map",         # Mean Arterial Pressure (mmHg)
    "shock_index", # Shock Index (HR / SYS)
    "hrv",         # Heart Rate Variability RMSSD (ms)
]

FEATURE_BOUNDS = {
    "hr":          (30, 220),
    "spo2":        (50, 100),
    "sys":         (50, 250),
    "dia":         (30, 160),
    "temp":        (33.0, 43.0),
    "rr":          (6, 60),
    "glucose":     (20, 500),
    "map":         (30, 180),
    "shock_index": (0.2, 2.5),
    "hrv":         (5, 150),
}

# ---------------------------------------------------------------------------
# Multi-Vital Risk Heuristic Computation
# ---------------------------------------------------------------------------

def _components(
    hr: np.ndarray,
    spo2: np.ndarray,
    sys_: np.ndarray,
    dia: np.ndarray,
    temp: np.ndarray,
    rr: np.ndarray,
    glucose: np.ndarray,
    map_: np.ndarray,
    shock_index: np.ndarray,
    hrv: np.ndarray,
) -> np.ndarray:
    """Compute per-vital deviation components (0 = normal, higher = worse)."""
    return np.array([
        # 1. Heart rate: Tachycardia > 100, Bradycardia < 55
        np.maximum((hr - 100) / 35, (55 - hr) / 22),
        # 2. Oxygen Saturation: Hypoxemia < 95
        (95 - spo2) / 7.5,
        # 3. Systolic BP: Hypertension > 140, Hypotension < 95
        np.maximum((sys_ - 140) / 38, (95 - sys_) / 22),
        # 4. Temperature: Pyrexia > 37.8, Hypothermia < 36.0
        np.maximum((temp - 37.8) / 1.4, (36.0 - temp) / 1.4),
        # 5. Respiratory Rate: Tachypnea > 20, Bradypnea < 12 (Critical ICU marker)
        np.maximum((rr - 20) / 8.0, (12 - rr) / 3.5),
        # 6. Blood Glucose: Hypoglycemia < 70 (high penalty), Hyperglycemia > 140
        np.maximum((glucose - 140) / 70.0, (70 - glucose) / 18.0),
        # 7. Mean Arterial Pressure: Loss of organ perfusion < 65 mmHg
        np.maximum((65 - map_) / 14.0, 0),
        # 8. Shock Index: HR / SYS > 0.70 indicating occult shock
        np.maximum((shock_index - 0.72) / 0.35, 0),
        # 9. HRV: Autonomic exhaustion / systemic inflammation < 25 ms
        np.maximum((25 - hrv) / 14.0, 0),
    ]).clip(min=0)


def generate_synthetic_data(n: int = 8000, seed: int = 42):
    """Generate synthetic vital-sign data across realistic clinical cohorts.

    Returns
    -------
    X : ndarray of shape (n, 10)
    y : ndarray of shape (n,)    - risk score in [0, 1]
    """
    rng = np.random.default_rng(seed)

    # Base vitals
    hr   = rng.normal(80, 24, n).clip(38, 200)
    spo2 = rng.normal(95.5, 4.2, n).clip(68, 100)
    sys_ = rng.normal(122, 26, n).clip(65, 230)
    dia  = (sys_ * 0.65 + rng.normal(0, 5, n)).clip(40, 135)
    temp = rng.normal(37.0, 0.85, n).clip(34.2, 41.2)
    rr   = rng.normal(16.5, 5.0, n).clip(8, 48)
    glucose = rng.normal(108, 38, n).clip(42, 380)

    # Derived hemodynamic features
    map_ = (2 * dia + sys_) / 3.0
    shock_index = hr / np.maximum(sys_, 1.0)
    hrv  = rng.normal(42, 16, n).clip(8, 110)

    # Add clinical correlation patterns to 25% of cases (Sepsis, Hypoglycemia, Shock)
    n_cris = int(n * 0.25)
    cris_idx = rng.choice(n, size=n_cris, replace=False)
    # Sepsis/Shock profile: Tachycardia + Tachypnea + Low BP + Low HRV + High Shock Index
    hr[cris_idx[:n_cris // 2]] += rng.uniform(25, 50, n_cris // 2)
    rr[cris_idx[:n_cris // 2]] += rng.uniform(8, 18, n_cris // 2)
    sys_[cris_idx[:n_cris // 2]] -= rng.uniform(20, 40, n_cris // 2)
    dia[cris_idx[:n_cris // 2]] -= rng.uniform(15, 25, n_cris // 2)
    hrv[cris_idx[:n_cris // 2]] = np.maximum(8, hrv[cris_idx[:n_cris // 2]] - rng.uniform(15, 25, n_cris // 2))

    # Hypoglycemia profile
    glucose[cris_idx[n_cris // 2:]] = rng.uniform(40, 58, n_cris - (n_cris // 2))
    hr[cris_idx[n_cris // 2:]] += rng.uniform(15, 30, n_cris - (n_cris // 2))

    # Recompute derived with clipped bounds
    hr = hr.clip(35, 205)
    sys_ = sys_.clip(55, 235)
    dia = dia.clip(35, 140)
    map_ = ((2 * dia + sys_) / 3.0).clip(35, 175)
    shock_index = (hr / np.maximum(sys_, 1.0)).clip(0.25, 2.3)
    rr = rr.clip(8, 52)
    glucose = glucose.clip(35, 420)
    hrv = hrv.clip(8, 120)

    # Calculate multi-vital risk components
    c = _components(hr, spo2, sys_, dia, temp, rr, glucose, map_, shock_index, hrv)
    y = (0.50 * c.max(axis=0) + 0.35 * c.mean(axis=0) * len(c) / 3.5 + 0.15 * (c[7] + c[6])
         + rng.normal(0, 0.015, n)).clip(0, 1)

    X = np.column_stack([hr, spo2, sys_, dia, temp, rr, glucose, map_, shock_index, hrv])
    return X, y


def train_model() -> RandomForestRegressor:
    """Train and return a RandomForestRegressor on synthetic data."""
    X, y = generate_synthetic_data(n=8000, seed=42)
    model = RandomForestRegressor(n_estimators=100, max_depth=14, n_jobs=-1, random_state=42)
    model.fit(X, y)
    return model


def train(n_samples: int = 8000, data_seed: int = 42,
          model_seed: int = 42, test_size: float = 0.2):
    """Train a RandomForestRegressor and persist artifacts.

    Returns
    -------
    dict with training metadata and train/test shapes.
    """
    print("=" * 60)
    print("Operation Ward Zero - Hospital-Grade ML Model Training (10 Features)")
    print("=" * 60)

    # 1. Generate data
    print(f"\n[1/4] Generating {n_samples} multi-parameter clinical samples (seed={data_seed}) ...")
    X, y = generate_synthetic_data(n=n_samples, seed=data_seed)
    print(f"      Feature matrix shape: {X.shape}")
    print(f"      Target range: [{y.min():.4f}, {y.max():.4f}]")

    # 2. Train / test split
    print(f"\n[2/4] Splitting data (test_size={test_size}) ...")
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=data_seed
    )
    print(f"      Train: {X_train.shape[0]}  |  Test: {X_test.shape[0]}")

    # 3. Compute feature statistics
    feature_stats = {
        "mean": X_train.mean(axis=0).tolist(),
        "std":  X_train.std(axis=0).tolist(),
        "names": FEATURE_NAMES,
        "bounds": FEATURE_BOUNDS,
    }

    # 4. Train model
    print("\n[3/4] Training RandomForestRegressor (100 estimators, max_depth=14) ...")
    t0 = time.time()
    model = RandomForestRegressor(
        n_estimators=100,
        max_depth=14,
        n_jobs=-1,
        random_state=model_seed,
    )
    model.fit(X_train, y_train)
    elapsed = time.time() - t0
    print(f"      Done in {elapsed:.2f}s")

    # 5. Persist artifacts
    print("\n[4/4] Saving model artifacts ...")
    joblib.dump(model, MODEL_PATH)
    print(f"      Model -> {MODEL_PATH}")
    joblib.dump(feature_stats, SCALER_PATH)
    print(f"      Stats -> {SCALER_PATH}")

    # Feature importances
    importances = dict(zip(FEATURE_NAMES, [round(float(v), 4) for v in model.feature_importances_]))
    print("\nFeature Importances:")
    for feat, imp in sorted(importances.items(), key=lambda x: x[1], reverse=True):
        bar = "#" * int(imp * 40)
        print(f"  {feat:12s}: {imp:.4f} {bar}")

    metadata = {
        "model_type": "RandomForestRegressor",
        "n_estimators": 100,
        "max_depth": 14,
        "n_features": len(FEATURE_NAMES),
        "feature_names": FEATURE_NAMES,
        "feature_importances": importances,
        "n_train_samples": int(X_train.shape[0]),
        "n_test_samples": int(X_test.shape[0]),
        "training_time_s": round(elapsed, 3),
        "data_seed": data_seed,
        "model_seed": model_seed,
        "artifacts": {
            "model": str(MODEL_PATH),
            "stats": str(SCALER_PATH),
        },
    }

    with open(TRAIN_REPORT_PATH, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)
    print(f"\nTraining report -> {TRAIN_REPORT_PATH}")
    print("\n[OK] Training complete.")
    return metadata


if __name__ == "__main__":
    train()
